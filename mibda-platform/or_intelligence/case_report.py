def default_frames(notes: list, phases: list, duration: float, limit: int = 8) -> list[dict]:
    """Evidence frames chosen from real timestamps only: the doctor's notes, then the start of each phase."""
    picks: list[dict] = []

    def add(t: float, cap: str) -> None:
        if 0 <= t <= max(duration, 0) and all(abs(t - p["t"]) >= 3 for p in picks):
            picks.append({"t": round(float(t), 1), "caption": cap})

    for n in notes[:5]:
        add(n["t_seconds"], "Doctor's note")
    for s in phases:
        add(s.start, "Start of phase (analysis)")
    return sorted(picks, key=lambda p: p["t"])[:limit]


def new_content(notes, phases, duration: float, lang: str = "en") -> dict:
    return {"version": 1, "language": lang, "ai": None, "doctor_comments": "",
            "frames": default_frames(notes, phases, duration)}


def _parse_json(text: str) -> dict:
    m = re.search(r"\{.*\}", text, re.S)
    if not m:
        raise llm.LLMError("Claude did not return a report draft. Try again.")
    try:
        return json.loads(m.group(0))
    except json.JSONDecodeError:
        raise llm.LLMError("Claude returned a malformed draft. Try again.") from None


def generate_ai(facts: dict, lang: str = "en") -> tuple[dict, llm.Result]:
    """Ask Claude for the AI part. Observations without valid supporting evidence labels are dropped."""
    chunks = casecontext.facts_to_chunks(facts)
    ctx = "\n".join(f"[{lab}] {txt}" for lab, _, txt in chunks)
    r = llm.complete(SYSTEM, [{"role": "user", "content": f"Language: {'Arabic' if lang == 'ar' else 'English'}\n\n<case_context>\n{ctx}\n</case_context>"}],
                     max_tokens=1500)
    d = _parse_json(r.text)
    valid = {lab for lab, _, _ in chunks}
    obs = []
    for o in d.get("observations", []):
        ev = [e for e in o.get("evidence", []) if e in valid]
        if str(o.get("text", "")).strip() and ev:
            obs.append({"text": str(o["text"]).strip(), "evidence": ev})
    ai = {"summary": str(d.get("summary", "")).strip(), "observations": obs,
          "limitations": str(d.get("limitations", "")).strip(), "model": r.model, "edited": False,
          "generated_at": int(time.time())}
    return ai, r


def build_pdf(path: str | Path, *, case, facts: dict, notes, content: dict, frames: list[tuple[float, bytes, str]],
              status: str, reviewer: str = "", lang: str = "en") -> str:
    """Write the PDF. `notes` are the raw doctor notes; `frames` = [(t, image bytes, caption)]. Returns the language used."""
    fonts = None
    if lang == "ar":
        fonts = base_report._register_font() if (base_report.arabic_reshaper and base_report.get_display) else None
        if fonts is None:
            lang = "en"
    ar = lang == "ar" and fonts is not None
    L = S[lang]
    fb, fbold = fonts if ar else ("Helvetica", "Helvetica-Bold")

    def sh(t) -> str:
        t = str(t)
        return base_report.get_display(base_report.arabic_reshaper.reshape(t)) if ar else t

    ss = getSampleStyleSheet()
    align = TA_RIGHT if ar else TA_LEFT
    body = ParagraphStyle("b", parent=ss["Normal"], fontName=fb, fontSize=9.5, leading=13.5, alignment=align)
    small = ParagraphStyle("s", parent=body, fontSize=8, leading=10.5, textColor=colors.HexColor("#555555"))
    h1 = ParagraphStyle("h1", parent=body, fontName=fbold, fontSize=18, leading=22, spaceAfter=4)
    h2 = ParagraphStyle("h2", parent=body, fontName=fbold, fontSize=11.5, leading=15, spaceBefore=12, spaceAfter=4,
                        textColor=colors.HexColor("#B26A24"))
    cell = ParagraphStyle("c", parent=body, fontSize=8.5, leading=11)
    head = ParagraphStyle("hc", parent=cell, fontName=fbold, textColor=colors.white)

    def esc(t) -> str:
        return sh(t).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    def P(t, st=body):
        return Paragraph(esc(t), st)

    def table(rows, widths, header=True):
        data = [[P(c, head if (header and r == 0) else cell) for c in row] for r, row in enumerate(rows)]
        t = Table(data, colWidths=widths, repeatRows=1 if header else 0)
        st = [("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#E3D3C6")), ("VALIGN", (0, 0), (-1, -1), "TOP"),
              ("TOPPADDING", (0, 0), (-1, -1), 3), ("BOTTOMPADDING", (0, 0), (-1, -1), 3)]
        if header:
            st += [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#B26A24")),
                   ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F2E9E1")])]
        t.setStyle(TableStyle(st))
        return t

    def banner(text, fg, bg):
        t = Table([[P(text, ParagraphStyle("bn", parent=body, fontName=fbold, textColor=colors.HexColor(fg)))]], colWidths=[width])
        t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(bg)), ("TOPPADDING", (0, 0), (-1, -1), 6),
                               ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
        return t

    width = A4[0] - 4 * cm
    story = [P(L["title"], h1)]
    story.append(banner(L["final"].format(name=reviewer or "-", date=time.strftime("%Y-%m-%d")) if status == "final" else L["draft"],
                        "#1f6b3a" if status == "final" else "#9a5b00", "#e3f5e9" if status == "final" else "#fdf0dd"))
    story += [Spacer(1, 6), P(L["overview"], h2), table([
        [L["case"], f'#{case["id"]} {case["title"]}'], [L["procedure"], facts["procedure"]],
        [L["duration"], fmt_time(facts["duration_s"])], [L["source"], facts["analysis_source"]],
        [L["created"], time.strftime("%Y-%m-%d %H:%M")]], [width * 0.28, width * 0.72], header=False)]

    story.append(P(L["analysis"], h2))
    if facts["phases"]:
        story.append(table([[L["phase"], L["start"], L["end"]]] + [[p["name"], fmt_time(p["start_s"]), fmt_time(p["end_s"])] for p in facts["phases"]],
                           [width * 0.5, width * 0.25, width * 0.25]))
    if facts["instruments"]:
        story += [Spacer(1, 5), table([[L["instrument"], L["active"], L["pct"]]] + [[i["name"], f'{i["active_s"]:.0f} s', f'{i["pct_of_case"]}%'] for i in facts["instruments"]],
                                      [width * 0.5, width * 0.25, width * 0.25])]
    if not facts["phases"] and not facts["instruments"]:
        story.append(P(L["none"]))
    if facts["flags"]:
        story.append(P(L["flags"], h2))
        for f in facts["flags"]:
            story.append(P(f"[{fmt_time(f['start_s'])} - {fmt_time(f['end_s'])}] {f['kind'].replace('_', ' ')} {f['instrument']}".strip()))

    story.append(P(L["doctor"], h2))
    if notes:
        story.append(table([[L["time"], L["by"], L["note"]]] + [[fmt_time(n["t_seconds"]), n["display_name"], n["text"]] for n in notes],
                           [width * 0.12, width * 0.23, width * 0.65]))
    else:
        story.append(P(L["none"]))
    if content.get("doctor_comments", "").strip():
        story += [P(L["comments"], h2), P(content["doctor_comments"])]

    ai = content.get("ai")
    if ai:
        story += [P(L["ai"], h2), banner(L["ai_note"].format(model=ai.get("model", "")), "#B26A24", "#F0DFD3"), Spacer(1, 4)]
        if ai.get("summary"):
            story += [P(L["summary"], ParagraphStyle("h3", parent=body, fontName=fbold)), P(ai["summary"])]
        if ai.get("observations"):
            story.append(P(L["obs"], ParagraphStyle("h3", parent=body, fontName=fbold, spaceBefore=6)))
            for o in ai["observations"]:
                story.append(P(f"• {o['text']}  ({L['evidence']}: {', '.join(o['evidence'])})"))
        if ai.get("limitations"):
            story += [P(L["limits"], ParagraphStyle("h3", parent=body, fontName=fbold, spaceBefore=6)), P(ai["limitations"])]

    if frames:
        story.append(P(L["frames"], h2))
        cells = []
        for t, png, cap in frames:
            img = Image(io.BytesIO(png), width=width / 2 - 8, height=(width / 2 - 8) * 0.5625)
            cells.append([[img, P(f"{fmt_time(t)}  {cap}", small)]])
        rows = [[c[0] for c in cells[i:i + 2]] + [""] * (2 - len(cells[i:i + 2])) for i in range(0, len(cells), 2)]
        gt = Table(rows, colWidths=[width / 2, width / 2])
        gt.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("BOTTOMPADDING", (0, 0), (-1, -1), 8)]))
        story.append(gt)

    story += [Spacer(1, 10), P(L["disclaimer"], small)]

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(colors.grey)
        canvas.drawString(2 * cm, 1.2 * cm, "MIBDA'  |  " + ("FINAL" if status == "final" else "DRAFT"))
        canvas.drawRightString(A4[0] - 2 * cm, 1.2 * cm, str(doc.page))
        canvas.restoreState()

    SimpleDocTemplate(str(path), pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm, topMargin=1.8 * cm,
                      bottomMargin=1.8 * cm, title="MIBDA case report").build(story, onFirstPage=footer, onLaterPages=footer)
    return lang

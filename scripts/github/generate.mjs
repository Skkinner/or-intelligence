#!/usr/bin/env node
// Owner: Member D. Regenerates planning artefacts from the single source of truth:
//   docs/planning/wbs_data.json  (+ .github/team.json for names / GitHub usernames)
//
// Outputs: .github/CODEOWNERS, .github/issues/manifest.json, TEAM_TASKS.md, PROJECT_PLAN.md,
//          REQUIREMENTS_CHECKLIST.md
//
// Usage:  node scripts/github/generate.mjs          (re-run after editing wbs_data.json or team.json)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), "utf8"));
const write = (p, s) => {
  mkdirSync(dirname(join(ROOT, p)), { recursive: true });
  writeFileSync(join(ROOT, p), s.replace(/\r\n/g, "\n"));
  console.log("wrote", p);
};

const D = read("docs/planning/wbs_data.json");
const TEAM = read(".github/team.json");
const tasks = D.tasks;
const byId = Object.fromEntries(tasks.map((t) => [t.id, t]));
const slots = Object.fromEntries(D.project.slots.map((s) => [s.id, s]));
const memberName = (id) => TEAM.members[id]?.name || `Member ${id}`;
const member = (id) => D.members.find((m) => m.id === id);
const phaseOf = (t) => t.id.split(".")[0];
const phaseName = (p) => D.phases.find((x) => x.id === p).name;
const wpName = (wp) => D.workPackages.find((x) => x.id === wp).name;
const slotLabel = (n) => `${slots[n].day} ${slots[n].part}`;
const when = (t) => (t.start === t.end ? slotLabel(t.start) : `${slotLabel(t.start)} → ${slotLabel(t.end)}`);
const isCritical = (t) => D.criticalPoints.includes(t.id);
const consumers = (t) => tasks.filter((x) => x.deps.includes(t.id));
const reqsFor = (t) => D.requirements.filter((r) => r.tasks.includes(t.id));
const TYPE = { 1: "planning", 2: "data", 3: "ml", 4: "backend", 5: "frontend", 6: "testing", 7: "integration", 8: "docs" };
const PHASE_SLUG = { 1: "planning", 2: "data", 3: "model", 4: "timeline-backend", 5: "web", 6: "testing", 7: "integration", 8: "delivery" };

function milestoneFor(t) {
  const gated = D.milestones.find((m) => m.gate.includes(t.id));
  if (gated) return gated;
  return D.milestones.find((m) => m.slot >= t.end) ?? D.milestones[D.milestones.length - 1];
}

// ---------------------------------------------------------------- CODEOWNERS
function codeowners() {
  const owners = new Map();
  for (const t of tasks) for (const f of t.files) owners.set(f, t.owner);
  for (const [p, o] of D.extraOwnership) if (!owners.has(p)) owners.set(p, o);
  const entries = [...owners.entries()].map(([p, o]) => [p.startsWith("/") ? p : `/${p}`, o]);
  const depth = (p) => p.replace(/\/$/, "").split("/").length + (p.endsWith("/") ? 0 : 0.5);
  entries.sort((a, b) => depth(a[0]) - depth(b[0]) || a[0].localeCompare(b[0]));
  const lines = [
    "# CODEOWNERS — generated by scripts/github/generate.mjs from docs/planning/wbs_data.json. Do not edit by hand.",
    "# Later lines win. Each path has exactly one owner (see TEAM_TASKS.md). Owner of this file: Member D.",
    "# Members without a GitHub username in .github/team.json are commented out and fall back to the default owner.",
    "",
  ];
  const fallback = TEAM.defaultOwner ? `@${TEAM.defaultOwner}` : null;
  lines.push(fallback ? `* ${fallback}` : "# * @<default-owner>   (set defaultOwner in .github/team.json)");
  for (const [p, o] of entries) {
    const gh = TEAM.members[o]?.github;
    lines.push(gh ? `${p.padEnd(44)} @${gh}` : `# ${p.padEnd(42)} ${memberName(o)} (github username not set)`);
  }
  return lines.join("\n") + "\n";
}

// ---------------------------------------------------------------- Issues
const issueRef = (id) => `{{#${id}}}`; // replaced with real issue numbers by setup_github.mjs
function issueBody(t) {
  const m = member(t.owner);
  const deps = t.deps.length
    ? t.deps.map((d) => `- [ ] ${issueRef(d)} WBS ${d} ${byId[d].name} (${memberName(byId[d].owner)})`).join("\n")
    : "- none, start immediately";
  const hand = consumers(t);
  const reqs = reqsFor(t);
  return [
    `**WBS ${t.id}** · Phase ${phaseOf(t)} ${phaseName(phaseOf(t))} · Work package ${t.wp} ${wpName(t.wp)}`,
    "",
    "| Owner | When | Effort | Priority | Branch |",
    "|---|---|---|---|---|",
    `| ${memberName(t.owner)} (${m.role}) | ${when(t)} | ${t.hours} h | ${t.priority} | \`${t.branch}\` |`,
    "",
    isCritical(t) ? "> ⚠ **Critical integration point**: other members are blocked on this task. Post progress at every merge window.\n" : "",
    t.addedBySetup ? "> ℹ Added during repository setup to cover a mandatory course-brief requirement.\n" : "",
    t.status === "Completed"
      ? "> ℹ The plan marks this task **Completed**. Commit the existing deliverable under the owned path, tick the criteria and close this issue.\n"
      : null,
    "## Description",
    t.desc,
    "",
    "",
    "## Steps",
    ...t.steps.map((s) => `- [ ] ${s}`),
    "",
    "## Files to modify (you own these)",
    ...t.files.map((f) => `- \`${f}\``),
    "",
    "Starter files with `TODO(" + t.owner + ", " + t.id + ")` markers are already in the repository where relevant. **They are not an implementation.**",
    "",
    "## Inputs",
    ...t.inputs.map((i) => `- ${i}`),
    "",
    "## Expected deliverables",
    ...t.outputs.map((o) => `- ${o}`),
    "",
    "## Depends on",
    deps,
    "",
    hand.length ? "## Hands off to\n" + hand.map((c) => `- ${issueRef(c.id)} WBS ${c.id} ${c.name} (${memberName(c.owner)})`).join("\n") + "\n\nWhen merged, tag the receiving member(s) in the PR.\n" : "",
    "## Acceptance criteria",
    ...t.accept.map((a) => `- [ ] ${a}`),
    "",
    "## Relevant requirements",
    reqs.length ? reqs.map((r) => `- **${r.id}** ${r.text} _(${r.source})_`).join("\n") : "- Supports the end-to-end pipeline (see REQUIREMENTS_CHECKLIST.md).",
    "",
    "## How to work on it",
    "```bash",
    "git switch develop && git pull",
    `git switch -c ${t.branch}`,
    "# edit only the files listed above, then:",
    `git add <your files> && git commit -m "[WBS ${t.id}] <what you did>"`,
    `git push -u origin ${t.branch}`,
    "```",
    `Open a PR into \`develop\` titled \`[WBS ${t.id}] ${t.name}\` and write \`Closes #<this issue>\` in the description.`,
  ].filter((x) => x !== null).join("\n").replace(/\n{3,}/g, "\n\n");
}

function labelsFor(t) {
  const p = phaseOf(t);
  const l = [`phase:${p}-${PHASE_SLUG[p]}`, `priority:${t.priority.toLowerCase()}`, `member:${t.owner.toLowerCase()}`, `type:${TYPE[p]}`];
  if (isCritical(t)) l.push("critical-path");
  if (t.addedBySetup) l.push("added-at-setup");
  return l;
}

function labels() {
  const L = [];
  const phaseColors = ["0e8a16", "1d76db", "5319e7", "0891b2", "d93f0b", "fbca04", "b60205", "006b75"];
  for (const ph of D.phases) L.push({ name: `phase:${ph.id}-${PHASE_SLUG[ph.id]}`, color: phaseColors[+ph.id - 1], description: `Phase ${ph.id}: ${ph.name}` });
  L.push({ name: "priority:high", color: "b60205", description: "High priority" });
  L.push({ name: "priority:medium", color: "fbca04", description: "Medium priority" });
  L.push({ name: "priority:low", color: "c2e0c6", description: "Low priority, cut first if late" });
  for (const m of D.members) L.push({ name: `member:${m.id.toLowerCase()}`, color: m.color.replace("#", ""), description: `${memberName(m.id)}: ${m.role}` });
  for (const ty of new Set(Object.values(TYPE))) L.push({ name: `type:${ty}`, color: "ededed", description: `${ty} work` });
  L.push({ name: "critical-path", color: "000000", description: "Critical integration point: others are blocked on it" });
  L.push({ name: "added-at-setup", color: "bfdadc", description: "Task added at repository setup to cover a course requirement" });
  L.push({ name: "bug", color: "d73a4a", description: "Something is broken (route to the owning member)" });
  L.push({ name: "contract-change", color: "e99695", description: "Change to contracts/: needs D + every affected consumer" });
  return L;
}

function manifest() {
  return {
    generated_from: "docs/planning/wbs_data.json",
    milestones: D.milestones.map((m) => ({ id: m.id, title: `${m.id} ${m.name}`, due_on: `${m.due}+03:00`, description: `${m.desc} Gate: ${m.gate.join(", ")}` })),
    labels: labels(),
    issues: tasks.map((t) => ({
      wbs: t.id,
      title: `[WBS ${t.id}] ${t.name}`,
      member: t.owner,
      labels: labelsFor(t),
      milestone: `${milestoneFor(t).id} ${milestoneFor(t).name}`,
      body: issueBody(t),
    })),
  };
}

// ---------------------------------------------------------------- TEAM_TASKS.md
function teamTasks() {
  const out = [
    "# Team Tasks",
    "",
    `> **${D.project.name}** · ${D.project.course} · Deadline **${D.project.deadlineLabel}**  `,
    "> Generated from `docs/planning/wbs_data.json` by `scripts/github/generate.mjs`. Names/usernames live in `.github/team.json`.",
    "",
    "Each member owns a disjoint set of files. **Edit only your own paths**; everything else is read-only for you.",
    "Every task is a GitHub Issue titled `[WBS x.y.z] …` with the label `member:<a|b|c|d>`.",
    "",
    "## Overview",
    "",
    "| Member | Role | Tasks | Hours | Branch prefix | Issues |",
    "|---|---|---|---|---|---|",
    ...D.members.map((m) => {
      const ts = tasks.filter((t) => t.owner === m.id);
      return `| ${memberName(m.id)} | ${m.role} | ${ts.length} | ${ts.reduce((a, t) => a + t.hours, 0)} | \`feature/member-${m.id.toLowerCase()}-\` | label \`member:${m.id.toLowerCase()}\` |`;
    }),
    "",
    "Work blocks: " + D.project.slots.map((s) => `**${s.id}** ${s.day} ${s.part} (${s.hours})`).join(" · "),
    "",
  ];
  for (const m of D.members) {
    const ts = tasks.filter((t) => t.owner === m.id);
    const files = [...new Set(ts.flatMap((t) => t.files))].sort();
    const receives = [...new Set(ts.flatMap((t) => t.deps).filter((d) => byId[d].owner !== m.id))];
    out.push("---", "", `## ${memberName(m.id)}: ${m.role}`, "", m.summary, "",
      `**Load:** ${ts.length} tasks · ${ts.reduce((a, t) => a + t.hours, 0)} h`, "",
      "### Start here", "",
      "```bash",
      "git clone <repo-url> && cd or-intelligence",
      "git switch develop",
      `git switch -c ${ts.find((t) => t.status !== "Completed")?.branch ?? ts[0].branch}`,
      "```", "",
      "### Your files (edit only these)", "", ...files.map((f) => `- \`${f}\``), "",
      "### Do not modify", "", ...m.notTouch.map((n) => `- ${n}`), "",
      "### You receive", "",
      ...(receives.length ? receives.map((d) => `- **${d}** ${byId[d].name} from ${memberName(byId[d].owner)} (${when(byId[d])})`) : ["- nothing: you can start immediately"]), "",
      "### Your tasks", "",
      "| WBS | Task | When | h | Priority | Branch | Depends on |",
      "|---|---|---|---|---|---|---|",
      ...ts.map((t) => `| ${t.id}${isCritical(t) ? " ⚠" : ""} | ${t.name} | ${when(t)} | ${t.hours} | ${t.priority} | \`${t.branch}\` | ${t.deps.join(", ") || "—"} |`), "");
    for (const t of ts) {
      out.push(`#### ${t.id} ${t.name}${t.status === "Completed" ? " (plan status: Completed)" : ""}`, "", t.desc, "",
        `**Files:** ${t.files.map((f) => `\`${f}\``).join(", ")}  `,
        `**Deliverables:** ${t.outputs.join("; ")}  `,
        `**Inputs:** ${t.inputs.join("; ")}`, "",
        "Completion checklist:", ...t.accept.map((a) => `- [ ] ${a}`), "- [ ] PR merged into `develop`; issue closed", "");
      const c = consumers(t).filter((x) => x.owner !== t.owner);
      if (c.length) out.push(`Hand-off: tag ${[...new Set(c.map((x) => memberName(x.owner)))].join(", ")} in the PR (needed for ${c.map((x) => x.id).join(", ")}).`, "");
    }
  }
  return out.join("\n");
}

// ---------------------------------------------------------------- PROJECT_PLAN.md
function projectPlan() {
  const out = [
    "# Project Plan",
    "",
    `> **${D.project.name}** · ${D.project.course} · Deadline **${D.project.deadlineLabel}**  `,
    "> Markdown version of `docs/planning/project_wbs_dashboard.html` (original task IDs and dependencies preserved).",
    "",
    `**${D.project.tagline}**`,
    "",
    D.project.description,
    "",
    "## Changes made at repository setup",
    "",
    ...D.setupNotes.map((n) => `- ${n}`),
    "",
    "## Schedule (work blocks)",
    "",
    "| Block | Day | Part | Hours |",
    "|---|---|---|---|",
    ...D.project.slots.map((s) => `| ${s.id} | ${s.day} | ${s.part} | ${s.hours} |`),
    "",
    "## Milestones",
    "",
    "| ID | Milestone | Due | Gate tasks | Meaning |",
    "|---|---|---|---|---|",
    ...D.milestones.map((m) => `| ${m.id} | ${m.name} | ${m.dueLabel} | ${m.gate.join(", ")} | ${m.desc} |`),
    "",
    "## Work Breakdown Structure",
    "",
  ];
  for (const ph of D.phases) {
    out.push(`### Phase ${ph.id} · ${ph.name}`, "");
    for (const wp of D.workPackages.filter((w) => w.phase === ph.id)) {
      out.push(`**${wp.id} ${wp.name}**`, "", "| WBS | Task | Owner | When | h | Priority | Depends on | Status |", "|---|---|---|---|---|---|---|---|");
      for (const t of tasks.filter((x) => x.wp === wp.id)) {
        out.push(`| ${t.id}${isCritical(t) ? " ⚠" : ""} | ${t.name}${t.addedBySetup ? " *(added at setup)*" : ""} | ${memberName(t.owner)} | ${when(t)} | ${t.hours} | ${t.priority} | ${t.deps.join(", ") || "—"} | ${t.status} |`);
      }
      out.push("");
    }
  }
  out.push("⚠ = critical integration point: " + D.criticalPoints.map((c) => `**${c}** ${byId[c].name}`).join(" · "), "",
    "## Dependencies (cross-member hand-offs)", "",
    "| Task | Owner | Needs | From |", "|---|---|---|---|",
    ...tasks.flatMap((t) => t.deps.filter((d) => byId[d].owner !== t.owner).map((d) => `| ${t.id} ${t.name} | ${memberName(t.owner)} | ${d} ${byId[d].name} | ${memberName(byId[d].owner)} |`)),
    "",
    "## Workload", "",
    "| Member | Role | Tasks | Hours |", "|---|---|---|---|",
    ...D.members.map((m) => { const ts = tasks.filter((t) => t.owner === m.id); return `| ${memberName(m.id)} | ${m.role} | ${ts.length} | ${ts.reduce((a, t) => a + t.hours, 0)} |`; }),
    "",
    "Member D's total includes the 6 h already spent on 1.1.1 and the 1 h for task 7.1.2 added at setup.", "",
    "## Conflicts resolved while planning", "",
    "| Issue | Resolution |", "|---|---|",
    ...D.resolutions.map((r) => `| ${r.issue} | ${r.fix} |`),
    "",
    "Risks, assumptions and cut list: see `docs/planning/WBS_VALIDATION.md`.", "");
  return out.join("\n");
}

// ---------------------------------------------------------------- REQUIREMENTS_CHECKLIST.md
function requirementsChecklist() {
  const owners = (ids) => [...new Set(ids.map((i) => memberName(byId[i].owner)))].join(", ");
  const uncovered = D.requirements.filter((r) => !r.tasks.length || r.tasks.some((x) => !byId[x]));
  const out = [
    "# Requirements Checklist",
    "",
    "> Every requirement mapped to the task(s) that deliver it and to the expected deliverable.  ",
    "> **P** = course brief (`docs/planning/Unit7_Project_brief.pdf`, authoritative). **R** = project page / success measures (WBS).  ",
    "> Generated from `docs/planning/wbs_data.json`. Tick a box only when the deliverable is merged into `develop`.",
    "",
    "## Course brief (mandatory)",
    "",
    "| Done | ID | Requirement | Tasks | Owners | Deliverable |", "|---|---|---|---|---|---|",
    ...D.requirements.filter((r) => r.id.startsWith("P")).map((r) => `| ☐ | ${r.id} | ${r.text} | ${r.tasks.join(", ")} | ${owners(r.tasks)} | ${r.deliverable} |`),
    "",
    "## Project requirements & success measures",
    "",
    "| Done | ID | Requirement | Source | Tasks | Owners | Deliverable |", "|---|---|---|---|---|---|---|",
    ...D.requirements.filter((r) => r.id.startsWith("R")).map((r) => `| ☐ | ${r.id} | ${r.text} | ${r.source} | ${r.tasks.join(", ")} | ${owners(r.tasks)} | ${r.deliverable} |`),
    "",
    "## Deliverables",
    "",
    "| ID | Deliverable | Produced by |", "|---|---|---|",
    ...D.deliverables.map((d) => `| ${d.id} | ${d.name} | ${d.tasks.map((t) => `${t} (${byId[t].owner})`).join(", ")} |`),
    "",
    "## Submission (Wed 25 Nov 23:59, milestone M7)",
    "",
    "- [ ] Presentation: `docs/slides/` (8.2.1, Member B)",
    "- [ ] Code repository: GitHub link, tag `v1.0.0` on `main` (7.2.1, Member D)",
    "- [ ] Deployment files: `scripts/run_local.*`, `docker/`, `docker-compose.yml` (7.1.1, 7.1.2, Member D)",
    "- [ ] Demo: live demo from the tagged build + backup video linked in `docs/demo/README.md` (7.2.1 D, 8.2.2 C)",
    "- [ ] Final report PDF built from `docs/report/` (8.1.4, Member D)",
    "",
    "## Coverage check",
    "",
    `- Requirements: ${D.requirements.length}, uncovered: ${uncovered.length ? uncovered.map((r) => r.id).join(", ") : "none"}.`,
    `- Tasks: ${tasks.length}, all with exactly one owner.`,
    "",
  ];
  return out.join("\n");
}

write(".github/CODEOWNERS", codeowners());
write(".github/issues/manifest.json", JSON.stringify(manifest(), null, 2) + "\n");
write("TEAM_TASKS.md", teamTasks());
write("PROJECT_PLAN.md", projectPlan());
write("REQUIREMENTS_CHECKLIST.md", requirementsChecklist());
